import { Text, View } from "react-native";

type Props = {
  family: string;
  description: string;
  medicinalProperties: string[];
  uses: string;
  preparation_method: string;
  origin: string;
  confidence: number;
  verified: boolean;
};

export default function PlantDetails({
  family,
  description,
  medicinalProperties,
  uses,
  preparation_method,
  origin,
  confidence,
  verified
}: Props) {
  const confidencePercentage = Math.round(confidence * 100);

  return (
    <View>

      {/* Description */}
      <Text
        style={{
          fontSize: 22,
          fontWeight: "700",
          marginBottom: 12,
        }}
      >
        Description
      </Text>

      <Text>{description || "No description available."}</Text>

      {/* Family */}
      <Text
        style={{
          fontSize: 22,
          fontWeight: "700",
          marginTop: 20,
          marginBottom: 12,
        }}
      >
        Family
      </Text>

      <Text>{family || "Unknown"}</Text>

      {/* Medicinal Properties */}
      <Text
        style={{
          fontSize: 22,
          fontWeight: "700",
          marginTop: 20,
          marginBottom: 12,
        }}
      >
        Medicinal Properties
      </Text>

      {medicinalProperties.length > 0 ? (
        medicinalProperties.map((property, index) => (
          <Text
            key={index}
            style={{ marginBottom: 6 }}
          >
            • {property}
          </Text>
        ))
      ) : (
        <Text>No medicinal properties available.</Text>
      )}

      {/* Uses */}
      <Text
        style={{
          fontSize: 22,
          fontWeight: "700",
          marginTop: 20,
          marginBottom: 12,
        }}
      >
        Uses
      </Text>

      <Text>{uses || "No information available."}</Text>

      {/* Preparation */}
      <Text
        style={{
          fontSize: 22,
          fontWeight: "700",
          marginTop: 20,
          marginBottom: 12,
        }}
      >
        Preparation
      </Text>

      <Text>{preparation_method || "No preparation information available."}</Text>

      {/* Origin */}
      <Text
        style={{
          fontSize: 22,
          fontWeight: "700",
          marginTop: 20,
          marginBottom: 12,
        }}
      >
        Origin
      </Text>

      <Text>{origin || "Unknown"}</Text>

      {/* AI Confidence */}
      <Text
        style={{
          fontSize: 22,
          fontWeight: "700",
          marginTop: 20,
          marginBottom: 12,
        }}
      >
        AI Confidence
      </Text>

      <Text>{confidencePercentage}%</Text>

      {/* Verification Status */}
    <Text
      style={{
        fontSize: 22,
        fontWeight: "700",
        marginTop: 20,
        marginBottom: 12,
      }}
    >
      Verification Status
    </Text>

    <View
      style={{
        alignSelf: "flex-start",
        backgroundColor: verified ? "#E8F5E9" : "#FFF3E0",
        borderColor: verified ? "#2E7D32" : "#F57C00",
        borderWidth: 1,
        borderRadius: 999,
        paddingHorizontal: 12,
        paddingVertical: 6,
      }}
    >
      <Text
        style={{
          color: verified ? "#2E7D32" : "#F57C00",
          fontWeight: "600",
        }}
      >
        {verified ? "✓ Verified" : "AI Generated"}
      </Text>
    </View>

    <Text
      style={{
        marginTop: 8,
        color: "#666",
        lineHeight: 20,
      }}
    >
      {verified
        ? "This plant information has been reviewed and verified."
        : "This information was generated by AI and has not yet been verified. Double-check important details before relying on it."}
    </Text>

    </View>
    

  );
}